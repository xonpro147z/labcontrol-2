/** Đa ngôn ngữ cho giao diện máy giáo viên. Khóa là câu tiếng Việt gốc; thiếu bản dịch thì hiện tiếng Việt.
 *  Thêm ngôn ngữ: thêm một bảng giống EN và một dòng trong LANGS. */
export type Lang = "vi" | "en";
export const LANGS: { code: Lang; name: string }[] = [
  { code: "vi", name: "Tiếng Việt" },
  { code: "en", name: "English" },
];

let current: Lang = "vi";
export function setLang(l: string | undefined) {
  if (l === "vi" || l === "en") current = l;
  else current = (typeof navigator !== "undefined" && !navigator.language.toLowerCase().startsWith("vi")) ? "en" : "vi";
  if (typeof document !== "undefined") document.documentElement.lang = current;
}
export function lang(): Lang { return current; }

/** Dịch câu tiếng Việt; {0}, {1}... được thay bằng tham số. */
export function tr(key: string, ...args: unknown[]): string {
  const s = current === "en" ? (EN[key] ?? key) : key;
  return args.length ? s.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? "")) : s;
}

